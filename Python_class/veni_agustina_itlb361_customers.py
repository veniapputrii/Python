# 2. To know amount of values in each category using .size counting it after .groupby finish grouping, further more, change the values of category into labels and make the amount of the category into rows, so it makes the visualization much more easier. Use fill_value=0 for removing the Na value (if it exists)
spending_counts = eda.groupby(
    ["Segmentation", "SpendingScore"]
).size().unstack(fill_value=0)
fig = px.bar(
    spending_counts,
    barmode="group",
    color_discrete_sequence=[yellow, maroon, sage_green],
    title="<b>Customer Spending Categories by Segment</b>"

)


"""You work for the "Best Company" and your job is to make email addresses for the employees. Define a function called make_email_addresses(L) that takes a list of strings (the names of the employees) and returns a dictionary that contains pairs of the format "name":"email address". The format of the email address is dot-separated (lower case) initials, then the last name(lower case) plus "@bestcompany.com". See the examples below.

HINT: Iterate over the list. Take the strings apart and extract the required parts. Assemble the email address. Accumulate the name:email pairs in a dictionary the way you saw in class.
"""

def make_email(L):
  email = {}
  for nama in L:
    #hahaaha split
    namanyadibagi = nama.lower().split()

    bagian_inisial = []
    #join
    for baginama in namanyadibagi[:-1]:
      bagian_inisial.append(baginama[0])
      masukin =  ".".join(bagian_inisial) #Veni Agustina Putri -> Veni.Agustina.Putri.

    result = masukin + "." + namanyadibagi[-1] + "@bestcompany.com"
    email[nama] = result
  return email

print(make_email(["James Tiberius Kirk", "Eve LeGrand", "Miles O'Brien"]))

"""Your company has a Python dictionary D in which it stores the wholesalers from which it buys and the set of the products it buys in the form compname:{product1, product2, ....}. Your task is to write a function distributors_and_products(D) that takes this dictionary and returns a 2-tuple: the first element is the list of all the companies that you buy from in alphabetic order; and the second element is the list of all the products that you buy, also in alphabetic order. See the examples below.

HINTS: Collect the distributors into a list. Accumulate the values by taking the union of the sets in the values of the items in the dictionary. Use sorted to turn the list of distributors and the set of products into lists sorted in alphabetic order. Return the ordered pair of the two lists.
"""

def distributors_and_products(D):
    perusahaan = []
    kabeh_dodolan = set()

    for kantor, dodolan in D.items():
        perusahaan.append(kantor)
        kabeh_dodolan.update(dodolan)

    ngurutne_perusahaan = sorted(perusahaan)
    ngurutne_dodolan = sorted(kabeh_dodolan)

    return (ngurutne_perusahaan, ngurutne_dodolan)

